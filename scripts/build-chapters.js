// build-chapters.js
// Reads all 13 markdown files and packages them into chapters-data.js
const fs = require('fs');
const path = require('path');

const phases = [
  {
    phaseId: 'phase-1',
    phaseName: 'Phase I: Language & Memory Foundations',
    range: '01-04',
    description: 'How syntax, engines, memory allocations, and data structures compose.',
    chapterNumbers: ['01', '02', '03', '04']
  },
  {
    phaseId: 'phase-2',
    phaseName: 'Phase II: Runtime Mechanics & Systems',
    range: '05-08',
    description: 'How execution contexts, prototypes, the DOM, and asynchronous loops operate.',
    chapterNumbers: ['05', '06', '07', '08']
  },
  {
    phaseId: 'phase-3',
    phaseName: 'Phase III: Architecture & Production Engineering',
    range: '09-13',
    description: 'Server protocols, modular design, TypeScript, and enterprise engineering.',
    chapterNumbers: ['09', '10', '11', '12', '13']
  }
];

const durations = {
  '01': '3-4 HOURS',
  '02': '2-3 HOURS',
  '03': '2-3 HOURS',
  '04': '2-3 HOURS',
  '05': '3-4 HOURS',
  '06': '2-3 HOURS',
  '07': '2-3 HOURS',
  '08': '3-4 HOURS',
  '09': '2-3 HOURS',
  '10': '2-3 HOURS',
  '11': '3-4 HOURS',
  '12': '2-3 HOURS',
  '13': '2-3 HOURS',
};

const chapterFiles = [
  '01-core-javascript.md',
  '02-functions.md',
  '03-data-structures.md',
  '04-modern-javascript-es6.md',
  '05-how-javascript-works.md',
  '06-object-oriented-javascript.md',
  '07-browser-and-dom.md',
  '08-asynchronous-javascript.md',
  '09-working-with-servers.md',
  '10-professional-javascript.md',
  '11-advanced-javascript.md',
  '12-typescript.md',
  '13-real-development.md'
];

const projectRoot = path.resolve(__dirname, '..');
const chaptersDir = path.join(projectRoot, 'chapters');
const outputDir = path.join(projectRoot, 'assets', 'js');
const chapters = [];

for (const filename of chapterFiles) {
  const filePath = path.join(chaptersDir, filename);
  if (!fs.existsSync(filePath)) {
    console.error(`File not found: ${filePath}`);
    continue;
  }

  const raw = fs.readFileSync(filePath, 'utf8');
  const lines = raw.split('\n');
  const numMatch = filename.match(/^(\d\d)/);
  const chNum = numMatch ? numMatch[1] : '01';

  // Extract Title from first header
  let title = 'Chapter ' + chNum;
  let rawTitle = '';
  for (const line of lines) {
    if (line.startsWith('# ')) {
      rawTitle = line.replace('# ', '').trim();
      // Clean up e.g. "Phase 1: Core JavaScript 🧱" -> "Core JavaScript"
      title = rawTitle.replace(/^Phase\s+\d+:\s*/i, '').trim();
      break;
    }
  }

  // Extract Goal / Subtitle
  let subtitle = '';
  for (const line of lines) {
    if (line.includes('> **Goal**:')) {
      subtitle = line.replace(/.*>\s*\*\*Goal\*\*:\s*/i, '').trim();
      break;
    }
  }
  if (!subtitle) {
    subtitle = `Deep exploration of ${title} with runtime internals and runnable code.`;
  }

  // Find phase
  const phaseObj = phases.find(p => p.chapterNumbers.includes(chNum)) || phases[0];

  // Extract Headings for TOC
  const toc = [];
  const headingRegex = /^(#{1,3})\s+(.*)$/gm;
  let hMatch;
  while ((hMatch = headingRegex.exec(raw)) !== null) {
    const level = hMatch[1].length;
    const text = hMatch[2].trim();
    // Skip the main document title and "Table of Contents"
    if (level === 1 && text.toLowerCase().startsWith('phase')) continue;
    if (text.toLowerCase() === 'table of contents') continue;
    
    // Create clean anchor id
    const id = text.toLowerCase()
      .replace(/[^\w\s-]/g, '')
      .trim()
      .replace(/\s+/g, '-');

    toc.push({
      level,
      text,
      id
    });
  }

  chapters.push({
    id: `chapter-${chNum}`,
    number: chNum,
    title,
    rawTitle,
    duration: durations[chNum] || '2-3 HOURS',
    subtitle,
    phaseId: phaseObj.phaseId,
    phaseName: phaseObj.phaseName,
    filename,
    toc,
    content: raw
  });
}

// Read practice.js
let practiceCode = '';
const practicePath = path.join(projectRoot, 'practice', 'practice.js');
if (fs.existsSync(practicePath)) {
  practiceCode = fs.readFileSync(practicePath, 'utf8');
}

const outputJs = `// Auto-generated by build-chapters.js
window.CHAPTERS_DATA = {
  phases: ${JSON.stringify(phases, null, 2)},
  chapters: ${JSON.stringify(chapters, null, 2)},
  practiceCode: ${JSON.stringify(practiceCode)}
};
`;

if (!fs.existsSync(outputDir)) {
  fs.mkdirSync(outputDir, { recursive: true });
}

fs.writeFileSync(path.join(outputDir, 'chapters-data.js'), outputJs, 'utf8');
console.log(`Successfully generated assets/js/chapters-data.js with ${chapters.length} chapters.`);
